import type { Plugin } from 'vite';
import { build } from 'esbuild';
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';

/**
 * Vite integration for the in-repo css-ts system (src/styling/core.ts).
 *
 * `*.styles.ts` modules are compile-time programs: they call
 * style()/globalStyle()/createGlobalTheme() and export class-name strings
 * and var() token objects. This plugin:
 *
 *  - `load`: evaluates the module in Node (bundled with esbuild) and
 *    replaces it with literal exports — so the app bundle contains plain
 *    strings and none of the styling machinery.
 *  - `buildStart`: evaluates every styles module under src/, de-duplicates
 *    shared rules (each module bundles the theme it imports), and writes
 *    the aggregate `src/cssts.gen.css`, imported by styles.css.
 *
 * Class names and CSS variable names are deterministic (file stem + name,
 * token path), so the two passes always agree and rebuilds are stable.
 */

const rootDir = resolve(__dirname, '..');
const srcDir = join(rootDir, 'src');
const REGISTRY_KEY = '__CSS_TS_REGISTRY__';
const VIRTUAL_PREFIX = '\0css-ts:';

interface Compiled {
  stub: string;
  rules: string[];
}

const cache = new Map<string, { mtimeMs: number; result: Compiled }>();

async function compileStylesModule(file: string): Promise<Compiled> {
  const mtimeMs = statSync(file).mtimeMs;
  const cached = cache.get(file);
  if (cached && cached.mtimeMs === mtimeMs) return cached.result;

  const bundled = await build({
    entryPoints: [file],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'node',
    target: 'node22',
    logLevel: 'silent',
  });
  const code = bundled.outputFiles[0].text;

  const scope = basename(file).replace(/\.styles\.ts$/, '').replace(/[^\w]/g, '_');
  const registry = { scope, rules: [] as string[] };
  (globalThis as Record<string, unknown>)[REGISTRY_KEY] = registry;
  const mod = { exports: {} as Record<string, unknown> };
  try {
    new Function('module', 'exports', 'require', code)(mod, mod.exports, () => {
      throw new Error(`css-ts: unexpected external require while evaluating ${file}`);
    });
  } finally {
    delete (globalThis as Record<string, unknown>)[REGISTRY_KEY];
  }

  const stub = Object.entries(mod.exports)
    .filter(([key]) => key !== '__esModule')
    .map(([key, value]) =>
      key === 'default'
        ? `export default ${JSON.stringify(value)};`
        : `export const ${key} = ${JSON.stringify(value)};`
    )
    .join('\n');

  const result = { stub, rules: registry.rules };
  cache.set(file, { mtimeMs, result });
  return result;
}

function findStylesModules(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (entry === 'node_modules' || entry.startsWith('.')) continue;
    if (statSync(full).isDirectory()) findStylesModules(full, out);
    else if (full.endsWith('.styles.ts')) out.push(full);
  }
  return out;
}

async function generateCss(): Promise<void> {
  const files = findStylesModules(srcDir).sort();
  const seen = new Set<string>();
  const rules: string[] = [];
  for (const file of files) {
    const { rules: fileRules } = await compileStylesModule(file);
    for (const rule of fileRules) {
      if (!seen.has(rule)) {
        seen.add(rule);
        rules.push(rule);
      }
    }
  }
  const outFile = join(srcDir, 'cssts.gen.css');
  const next =
    '/* AUTO-GENERATED by vite-plugins/css-ts.ts — do not edit. */\n' +
    rules.join('\n') +
    '\n';
  const prev = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (prev !== next) writeFileSync(outFile, next);
}

export function cssTsPlugin(): Plugin[] {
  return [
    {
      name: 'blog-css-ts',
      enforce: 'pre',
      async buildStart() {
        await generateCss();
      },
      async handleHotUpdate(ctx) {
        if (ctx.file.endsWith('.styles.ts') || ctx.file.endsWith('/core.ts')) {
          await generateCss();
        }
      },
    },
    {
      // Replaces each compiled *.styles module with its literal exports.
      // enforce: 'post' so it runs AFTER the Angular compiler, which
      // re-emits .ts modules from its own TypeScript program and would
      // otherwise overwrite the stub (module ids may be extensionless
      // because components import './x.styles').
      name: 'blog-css-ts:stub',
      enforce: 'post',
      async transform(_code, id) {
        const file = id.split('?')[0];
        if (!file.endsWith('.styles') && !file.endsWith('.styles.ts')) return null;
        const real = file.endsWith('.ts') ? file : file + '.ts';
        if (!existsSync(real)) return null;
        const { stub } = await compileStylesModule(real);
        return { code: stub, map: null };
      },
    },
  ];
}
