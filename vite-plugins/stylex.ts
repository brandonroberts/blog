import type { Plugin } from 'vite';
import { transformAsync } from '@babel/core';
import stylexBabelPlugin from '@stylexjs/babel-plugin';
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';

/**
 * Minimal StyleX integration for the Analog/Angular Vite pipeline.
 *
 * StyleX has no official Vite plugin, and the community `vite-plugin-stylex`
 * is pinned to StyleX 0.9 / Vite 5, so this does the two required jobs
 * directly with the official Babel plugin:
 *
 * 1. `transform` (enforce: 'post') — runs AFTER the Angular compiler has
 *    turned component TypeScript into JS, replacing `stylex.create/defineVars/
 *    createTheme` calls with compiled class-name/variable objects. Without
 *    this, the StyleX runtime throws at runtime.
 *
 * 2. `buildStart` — scans `src/` for files importing `@stylexjs/stylex`,
 *    extracts their style rules, and writes the aggregate `src/stylex.gen.css`
 *    (imported by `styles.css`). Class name hashes are content-based, so the
 *    names produced here match the ones produced by the transform in (1).
 */

const rootDir = resolve(__dirname, '..');

const stylexOptions = {
  dev: false,
  runtimeInjection: false,
  treeshakeCompensation: true,
  unstable_moduleResolution: { type: 'commonJS' as const, rootDir },
};

const babelParserPlugins = [
  'typescript',
  ['decorators', { version: '2023-05' }],
] as any[];

function walkTsFiles(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (entry === 'node_modules' || entry.startsWith('.')) continue;
    if (statSync(full).isDirectory()) {
      walkTsFiles(full, out);
    } else if (full.endsWith('.ts') && !full.endsWith('.spec.ts') && !full.endsWith('.d.ts')) {
      out.push(full);
    }
  }
  return out;
}

async function generateStylexCss(): Promise<void> {
  const srcDir = join(rootDir, 'src');
  const files = walkTsFiles(srcDir).filter((f) =>
    readFileSync(f, 'utf8').includes('@stylexjs/stylex')
  );

  const rules: any[] = [];
  for (const file of files) {
    const code = readFileSync(file, 'utf8');
    const result = await transformAsync(code, {
      filename: file,
      babelrc: false,
      configFile: false,
      parserOpts: { plugins: babelParserPlugins },
      plugins: [[stylexBabelPlugin, stylexOptions]],
    });
    const metadata = result?.metadata as { stylex?: any[] } | undefined;
    if (metadata?.stylex?.length) {
      rules.push(...metadata.stylex);
    }
  }

  // De-duplicate rules shared across modules before generating CSS.
  const unique = [...new Map(rules.map((r) => [JSON.stringify(r), r])).values()];
  const css = (stylexBabelPlugin as any).processStylexRules(unique);

  const outFile = join(srcDir, 'stylex.gen.css');
  const banner = '/* AUTO-GENERATED by vite-plugins/stylex.ts — do not edit. */\n';
  const next = banner + css + '\n';
  const prev = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (prev !== next) {
    writeFileSync(outFile, next);
  }
}

export function stylexPlugin(): Plugin {
  return {
    name: 'blog-stylex',
    enforce: 'post',
    async buildStart() {
      await generateStylexCss();
    },
    async handleHotUpdate(ctx) {
      if (ctx.file.endsWith('.ts')) {
        await generateStylexCss();
      }
    },
    async transform(code, id) {
      const [filename] = id.split('?');
      if (!/\.[cm]?[jt]sx?$/.test(filename)) return null;
      if (!code.includes('@stylexjs/stylex')) return null;

      const result = await transformAsync(code, {
        filename,
        babelrc: false,
        configFile: false,
        parserOpts: { plugins: babelParserPlugins },
        plugins: [[stylexBabelPlugin, stylexOptions]],
      });

      if (!result?.code) return null;
      return { code: result.code, map: result.map };
    },
  };
}
